
/* buatlah program yang menampilkan bilangan genap dari 2 hingga 20 menggunakan perulangan for*/
#include <iostream>
using namespace std;

int main (){
    cout << "bilangan genap antara 2-20: " << endl;
    for (int i = 2; i <= 20; i +=2){
        cout << i << endl;
    }
    return 0;
}
